#!/usr/bin/env bash
# Installed root-owned outside runner-writable releases. Overrides are for the
# isolated integration test; systemd uses the fixed production defaults.
set -Eeuo pipefail
umask 077
export PATH=/usr/local/bin:/usr/bin:/bin
release=${HA_RELEASE:-$(readlink -f /ScaleTag/current)}
revision=${release##*/}
[[ "$revision" =~ ^[0-9a-f]{40}$ ]] || { echo 'Invalid revision'; exit 1; }
state=${HA_STATE_DIR:-/ScaleTag/ha}
config=${HA_COMPOSE:-/etc/scaletag-ha/compose.ha.yaml}
envfile=${HA_ENV_FILE:-/etc/scaletag.env}
project=${HA_PROJECT:-scaletag-ha}
export SCALETAG_DATA_SOURCE=${SCALETAG_DATA_SOURCE:-/ScaleTag/data}
if [[ "$SCALETAG_DATA_SOURCE" == /* ]]; then
  export SCALETAG_UID=${SCALETAG_UID:-$(stat -c %u "$SCALETAG_DATA_SOURCE")}
  export SCALETAG_GID=${SCALETAG_GID:-$(stat -c %g "$SCALETAG_DATA_SOURCE")}
  [[ "$SCALETAG_UID" -gt 0 && "$SCALETAG_GID" -gt 0 ]] || { echo 'Non-root data owner required'; exit 1; }
fi
mkdir -p "$state"
exec 8>"$state/.rollout.lock"
flock -n 8 || { echo 'Another HA rollout is in progress'; exit 1; }
compose() { docker compose --project-name "$project" --env-file "$envfile" --file "$config" "$@"; }
save() {
  printf 'APP1_IMAGE=%s\nAPP1_REVISION=%s\nAPP2_IMAGE=%s\nAPP2_REVISION=%s\n' \
    "$APP1_IMAGE" "$APP1_REVISION" "$APP2_IMAGE" "$APP2_REVISION" > "$state/.images.next"
  mv -f "$state/.images.next" "$state/images.env"
}
wait_slot() { compose up --detach --no-deps --no-build --wait --wait-timeout 60 "$1"; }
route() {
  local slot=$1 rev=$2 probe=${3:-app2}
  # Fetch through ingress from inside the private network. No diagnostic app
  # ports or Docker socket are exposed to cloudflared/the runner.
  for attempt in {1..25}; do
    if compose exec -T "$probe" node --input-type=module -e '
      const r=await fetch("http://ingress:8080/readyz",{signal:AbortSignal.timeout(3000)});
      const d=await r.json();
      if(!r.ok||d.instance!==process.argv[1]||d.revision!==process.argv[2])process.exit(1);
    ' "$slot" "$rev" >/dev/null 2>&1; then return; fi
    sleep 1
  done
  echo "Ingress did not route to $slot at expected revision" >&2
  return 1
}
image="scaletag:$revision"
docker image inspect "$image" >/dev/null 2>&1 || \
  docker build --pull --build-arg SYSTEM_UPDATE_REVISION="$revision" --tag "$image" "$release"
# Check source readability as the real runtime UID before touching either slot.
docker run --rm --user "${SCALETAG_UID:-1000}:${SCALETAG_GID:-1000}" \
  --read-only --network none --cap-drop ALL --security-opt no-new-privileges:true \
  --memory 256m --pids-limit 32 --entrypoint node "$image" --input-type=module -e '
    import {readFileSync} from "node:fs";
    JSON.parse(readFileSync("/app/package.json"));
    readFileSync("/app/public/index.html");
    await import("/app/src/sqlite-store.js");
  '
if [[ ! -f "$state/images.env" ]]; then
  export APP1_IMAGE=$image APP2_IMAGE=$image APP1_REVISION=$revision APP2_REVISION=$revision
  save
  wait_slot app1
  wait_slot app2
  compose up --detach --no-deps ingress
  route app1 "$revision"
  echo "HA initialized at $revision"
  exit 0
fi
# This file is generated by this helper, root-owned and contains no secrets.
source "$state/images.env"
export APP1_IMAGE APP2_IMAGE APP1_REVISION APP2_REVISION
old1=$APP1_IMAGE oldrev1=$APP1_REVISION old2=$APP2_IMAGE oldrev2=$APP2_REVISION
phase=backup
rollback() {
  local code=$?
  trap - ERR
  set +e
  if [[ "$phase" == backup ]]; then
    APP2_IMAGE=$old2 APP2_REVISION=$oldrev2
    save; wait_slot app2
    echo 'Standby update failed; primary was left serving.' >&2
  else
    APP1_IMAGE=$old1 APP1_REVISION=$oldrev1
    save; wait_slot app1
    echo 'Primary update failed; retained new standby and attempted primary rollback.' >&2
  fi
  exit "$code"
}
# Establish a healthy primary before replacing the standby. If primary is
# already down, recover it first rather than taking the only serving slot away.
wait_slot app1
compose up --detach --no-deps ingress
route app1 "$oldrev1" app1
trap rollback ERR
APP2_IMAGE=$image APP2_REVISION=$revision
save
wait_slot app2
# Allow Nginx's 1-second Docker DNS cache to learn the replacement standby's IP
# before taking the primary offline. Application readiness alone is not enough.
sleep 2
echo 'Updated app2; readiness passed. Taking app1 offline.'
phase=primary
compose stop --timeout 15 app1
route app2 "$revision"
echo 'Ingress failed over to app2; updating app1.'
APP1_IMAGE=$image APP1_REVISION=$revision
save
wait_slot app1
route app1 "$revision"
trap - ERR
echo "HA rollout complete: app1 preferred, both slots at $revision"
